import Foundation

struct ElectoralState: Codable, Identifiable, Equatable {
    let name: String
    let lat: Double
    let lng: Double
    let ev: Int

    var id: String { name }
}

struct StateShape: Codable, Identifiable {
    let name: String
    let d: String
    var id: String { name }
}

struct StatePaths: Codable {
    struct ViewBox: Codable {
        let width: Double
        let height: Double
    }
    let viewBox: ViewBox
    let shapes: [StateShape]
}

struct OfficialLink: Codable, Identifiable {
    let label: String
    let source: String
    let href: String
    var id: String { href }
}

/// Everything here ships in the bundle, so the Map tab and the official-links fallback work with
/// no network at all. Generated by `scripts/export-ios-data.mjs` from the web app's own data.
enum BundledData {
    static let states: [ElectoralState] = load("states.json")
    static let statePaths: StatePaths = load("statePaths.json")
    static let officialLinks: [OfficialLink] = load("officialLinks.json")
    static let statesAlphabetically = states.sorted { $0.name < $1.name }

    static var totalElectoralVotes: Int { states.reduce(0) { $0 + $1.ev } }

    private static func load<T: Decodable>(_ name: String) -> T {
        guard let url = Bundle.main.url(forResource: name, withExtension: nil),
            let data = try? Data(contentsOf: url)
        else {
            // These files are compiled into the app; absence is a build error, not a runtime state.
            fatalError("Missing bundled resource \(name) — run scripts/export-ios-data.mjs")
        }
        do {
            return try JSONDecoder().decode(T.self, from: data)
        } catch {
            fatalError("Could not decode \(name): \(error)")
        }
    }
}
